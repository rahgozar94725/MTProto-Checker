// Returns undefined for an unknown locale or key — callers decide the fallback, the same
// way setLanguage() leaves the markup untouched when a key is absent.
export function t(lang, key) {
    const table = translations[lang];
    return table ? table[key] : undefined;
}

// Replaces {name} placeholders from vars. A placeholder with no matching variable is left
// as-is, and substituted values are never rescanned for further placeholders.
export function interpolate(str, vars) {
    if (!vars) return str;
    return str.replace(/\{(\w+)\}/g, (match, name) =>
        Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
    );
}
